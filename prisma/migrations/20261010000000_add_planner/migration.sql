-- ============================================================================
-- Fase 5 (Planner) — reconciliação de schema com migrations legadas locais.
--
-- Contexto: o banco local já continha planner_tasks/weekly_plans/weekly_goals
-- e o enum PlannerCategory via migrations não rastreadas em
-- prisma/migrations (add_planner_system, add_planner_fields_to_streak_history).
-- Esta migration é, portanto, IDEMPOTENTE: em um banco fresco (CI) ela cria
-- tudo; em um banco com as tabelas legadas ela apenas adiciona o que falta
-- (kanjiGlyph, name/kanjiGlyph/currentValue, createdAt/updatedAt de
-- weekly_goals, planner_history + índices/FKs ausentes) sem perder dados.
-- ============================================================================

-- Enums: cria somente se ainda não existirem
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'PlannerCategory') THEN
    CREATE TYPE "PlannerCategory" AS ENUM ('KANJI', 'VOCABULARY', 'GRAMMAR', 'CHUNK', 'READING', 'IMMERSION', 'ACTIVE_STUDY', 'PASSIVE_STUDY', 'REVIEW', 'GENERAL', 'OTHER');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'PlannerTaskPriority') THEN
    CREATE TYPE "PlannerTaskPriority" AS ENUM ('LOW', 'MEDIUM', 'HIGH');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'PlannerTaskStatus') THEN
    CREATE TYPE "PlannerTaskStatus" AS ENUM ('PENDING', 'COMPLETED');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'WeeklyPlanStatus') THEN
    CREATE TYPE "WeeklyPlanStatus" AS ENUM ('ACTIVE', 'COMPLETED', 'ARCHIVED');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'PlannerGoalCategory') THEN
    CREATE TYPE "PlannerGoalCategory" AS ENUM ('IMMERSION', 'KANJI', 'VOCABULARY', 'GRAMMAR', 'GENERAL_REVIEW', 'READING', 'ACTIVE_STUDY', 'PASSIVE_STUDY');
  END IF;
END
$$;

-- Tabelas: cria somente se ainda não existirem (legado já as possui)
CREATE TABLE IF NOT EXISTS "planner_tasks" (
    "id" TEXT NOT NULL,
    "userId" TEXT NOT NULL,
    "weeklyPlanId" TEXT,
    "title" VARCHAR(300) NOT NULL,
    "description" TEXT,
    "category" "PlannerCategory" NOT NULL DEFAULT 'GENERAL',
    "kanjiGlyph" VARCHAR(8) NOT NULL DEFAULT '全',
    "date" VARCHAR(10) NOT NULL,
    "scheduledTime" VARCHAR(5),
    "estimatedMinutes" INTEGER NOT NULL DEFAULT 20,
    "actualMinutes" INTEGER,
    "priority" "PlannerTaskPriority" NOT NULL DEFAULT 'MEDIUM',
    "status" "PlannerTaskStatus" NOT NULL DEFAULT 'PENDING',
    "completedAt" TIMESTAMP(3),
    "isAutoGenerated" BOOLEAN NOT NULL DEFAULT false,
    "actionPayload" JSONB,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "planner_tasks_pkey" PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "weekly_plans" (
    "id" TEXT NOT NULL,
    "userId" TEXT NOT NULL,
    "year" INTEGER NOT NULL,
    "weekNumber" INTEGER NOT NULL,
    "startDate" VARCHAR(10) NOT NULL,
    "endDate" VARCHAR(10) NOT NULL,
    "status" "WeeklyPlanStatus" NOT NULL DEFAULT 'ACTIVE',
    "notes" TEXT,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "weekly_plans_pkey" PRIMARY KEY ("id")
);

-- Coluna física legada: "weeklyPlanId" (mapeada para planId no Prisma via @map)
CREATE TABLE IF NOT EXISTS "weekly_goals" (
    "id" TEXT NOT NULL,
    "weeklyPlanId" TEXT NOT NULL,
    "category" "PlannerGoalCategory" NOT NULL,
    "name" VARCHAR(100) NOT NULL DEFAULT '?',
    "kanjiGlyph" VARCHAR(8) NOT NULL DEFAULT '?',
    "targetValue" INTEGER NOT NULL DEFAULT 0,
    "currentValue" INTEGER NOT NULL DEFAULT 0,
    "unit" VARCHAR(20) NOT NULL DEFAULT '',
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "weekly_goals_pkey" PRIMARY KEY ("id")
);

CREATE TABLE IF NOT EXISTS "planner_history" (
    "id" TEXT NOT NULL,
    "taskId" TEXT NOT NULL,
    "oldStatus" "PlannerTaskStatus" NOT NULL,
    "newStatus" "PlannerTaskStatus" NOT NULL,
    "changedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "planner_history_pkey" PRIMARY KEY ("id")
);

-- Colunas ausentes no legado (no-op em banco fresco)
ALTER TABLE "planner_tasks" ADD COLUMN IF NOT EXISTS "kanjiGlyph" VARCHAR(8) NOT NULL DEFAULT '全';
ALTER TABLE "weekly_goals" ADD COLUMN IF NOT EXISTS "name" VARCHAR(100) NOT NULL DEFAULT '?';
ALTER TABLE "weekly_goals" ADD COLUMN IF NOT EXISTS "kanjiGlyph" VARCHAR(8) NOT NULL DEFAULT '?';
ALTER TABLE "weekly_goals" ADD COLUMN IF NOT EXISTS "currentValue" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE "weekly_goals" ADD COLUMN IF NOT EXISTS "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE "weekly_goals" ADD COLUMN IF NOT EXISTS "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- Índices (nomes conforme convenção Prisma; índices legados com sufixo semanal preservados)
CREATE INDEX IF NOT EXISTS "planner_tasks_userId_date_idx" ON "planner_tasks"("userId", "date");
CREATE INDEX IF NOT EXISTS "planner_tasks_userId_status_idx" ON "planner_tasks"("userId", "status");
CREATE INDEX IF NOT EXISTS "planner_tasks_userId_date_status_idx" ON "planner_tasks"("userId", "date", "status");
CREATE INDEX IF NOT EXISTS "planner_tasks_weeklyPlanId_idx" ON "planner_tasks"("weeklyPlanId");
CREATE INDEX IF NOT EXISTS "planner_history_taskId_changedAt_idx" ON "planner_history"("taskId", "changedAt" DESC);
CREATE INDEX IF NOT EXISTS "weekly_plans_userId_startDate_idx" ON "weekly_plans"("userId", "startDate");
CREATE UNIQUE INDEX IF NOT EXISTS "weekly_plans_userId_year_weekNumber_key" ON "weekly_plans"("userId", "year", "weekNumber");
CREATE INDEX IF NOT EXISTS "weekly_goals_planId_idx" ON "weekly_goals"("weeklyPlanId");
CREATE UNIQUE INDEX IF NOT EXISTS "weekly_goals_planId_category_key" ON "weekly_goals"("weeklyPlanId", "category");

-- Foreign keys: adiciona somente se ainda não existirem
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'planner_tasks_userId_fkey') THEN
    ALTER TABLE "planner_tasks" ADD CONSTRAINT "planner_tasks_userId_fkey" FOREIGN KEY ("userId") REFERENCES "users"("id") ON DELETE CASCADE ON UPDATE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'planner_tasks_weeklyPlanId_fkey') THEN
    ALTER TABLE "planner_tasks" ADD CONSTRAINT "planner_tasks_weeklyPlanId_fkey" FOREIGN KEY ("weeklyPlanId") REFERENCES "weekly_plans"("id") ON DELETE SET NULL ON UPDATE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'planner_history_taskId_fkey') THEN
    ALTER TABLE "planner_history" ADD CONSTRAINT "planner_history_taskId_fkey" FOREIGN KEY ("taskId") REFERENCES "planner_tasks"("id") ON DELETE CASCADE ON UPDATE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'weekly_plans_userId_fkey') THEN
    ALTER TABLE "weekly_plans" ADD CONSTRAINT "weekly_plans_userId_fkey" FOREIGN KEY ("userId") REFERENCES "users"("id") ON DELETE CASCADE ON UPDATE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'weekly_goals_weeklyPlanId_fkey') THEN
    ALTER TABLE "weekly_goals" ADD CONSTRAINT "weekly_goals_weeklyPlanId_fkey" FOREIGN KEY ("weeklyPlanId") REFERENCES "weekly_plans"("id") ON DELETE CASCADE ON UPDATE CASCADE;
  END IF;
END
$$;

