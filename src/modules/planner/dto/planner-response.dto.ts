import {
  PlannerGoalCategory,
  PlannerCategory,
  PlannerTaskPriority,
  PlannerTaskStatus,
  WeeklyPlanStatus,
} from '@prisma/client';

export type PlannerTaskAction =
  | { type: 'review_kanji'; count: number }
  | { type: 'review_vocabulary'; count: number }
  | { type: 'study_grammar'; count: number }
  | { type: 'immersion'; targetMinutes: number; loggedMinutes: number }
  | { type: 'daily_review'; targetCount: number; completedCount: number }
  | { type: 'general'; note: string };

export interface PlannerTaskItemResponseDto {
  id: string;
  userId: string;
  weeklyPlanId: string | null;
  title: string;
  description: string | null;
  category: PlannerCategory;
  categoryLabel: string;
  kanjiGlyph: string;
  date: string;
  scheduledTime: string | null;
  estimatedMinutes: number;
  actualMinutes: number | null;
  priority: PlannerTaskPriority;
  status: PlannerTaskStatus;
  completedAt: string | null;
  isAutoGenerated: boolean;
  actionPayload: Record<string, unknown> | null;
  createdAt: string;
  updatedAt: string;
}

export interface PlannerHistoryItemResponseDto {
  id: string;
  taskId: string;
  oldStatus: PlannerTaskStatus;
  newStatus: PlannerTaskStatus;
  changedAt: string;
}

export interface WeeklyGoalResponseDto {
  id: string;
  category: PlannerGoalCategory;
  name: string;
  kanjiGlyph: string;
  targetValue: number;
  currentValue: number;
  percentage: number;
  unit: string;
}

export interface WeeklyPlanResponseDto {
  id: string;
  userId: string;
  year: number;
  weekNumber: number;
  startDate: string;
  endDate: string;
  status: WeeklyPlanStatus;
  notes: string | null;
  goals: WeeklyGoalResponseDto[];
  createdAt: string;
  updatedAt: string;
}

export interface TodaySummaryResponseDto {
  totalTasks: number;
  completedTasks: number;
  pendingTasks: number;
  completionPercentage: number;
  minutesStudied: number;
  categoriesStudied: string[];
  streak: number;
}

export type PlannerTaskDomain =
  | 'kanji'
  | 'vocabulary'
  | 'grammar'
  | 'immersion'
  | 'general';

export interface PlannerOverviewTaskDto {
  id: string;
  domain: PlannerTaskDomain;
  task: string;
  description: string | null;
  priority: 'high' | 'medium' | 'low';
  estimatedMinutes: number;
  kanjiGlyph: string;
  dueAt: string;
  status: PlannerTaskStatus;
  completed: boolean;
  action: PlannerTaskAction;
}

export interface PlannerWeekDayDto {
  date: number;
  day: string;
  isToday: boolean;
}

export interface PlannerHabitDto {
  id: string;
  name: string;
  kanji: string;
  domain: PlannerTaskDomain;
  streak: number;
  completedThisWeek: boolean[];
  weeklyTarget: number;
}

export interface PlannerWeeklyGoalDto {
  name: string;
  kanji: string;
  current: number;
  target: number;
  unit: string;
}

export interface PlannerSummaryDto {
  tasksCompletedToday: number;
  tasksPendingToday: number;
  tasksTotalToday: number;
  completionPercentage: number;
  studyMinutesToday: number;
  categoriesStudiedToday: string[];
  currentStreakDays: number;
  longestStreakDays: number;
  todayDateLabel: string;
}

export interface PlannerOverviewResponseDto {
  week: PlannerWeekDayDto[];
  habits: PlannerHabitDto[];
  todayTasks: PlannerOverviewTaskDto[];
  weeklyGoals: PlannerWeeklyGoalDto[];
  summary: PlannerSummaryDto;
}

export interface DeletePlannerTaskResponseDto {
  success: boolean;
  id: string;
}
