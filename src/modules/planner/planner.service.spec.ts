import { Test, TestingModule } from '@nestjs/testing';
import { NotFoundException } from '@nestjs/common';
import {
  PlannerGoalCategory,
  PlannerTask,
  PlannerCategory,
  PlannerTaskPriority,
  PlannerTaskStatus,
  WeeklyGoal,
  WeeklyPlan,
  WeeklyPlanStatus,
} from '@prisma/client';
import { PlannerService } from './planner.service';
import { PlannerRepository } from './repositories';
import { DEFAULT_TIMEZONE } from './planner.constants';
import { todayInTz } from './planner-date.util';

describe('PlannerService', () => {
  let service: PlannerService;
  type RepositoryMocks = { [K in keyof PlannerRepository]: jest.Mock };
  let repository: RepositoryMocks;

  const userId = 'user-1';
  const today = todayInTz(DEFAULT_TIMEZONE);

  const buildTask = (overrides: Partial<PlannerTask> = {}): PlannerTask => ({
    id: 'task-1',
    userId,
    weeklyPlanId: 'plan-1',
    title: 'Revisar kanjis',
    description: null,
    category: PlannerCategory.KANJI,
    kanjiGlyph: '字',
    date: today,
    scheduledTime: '19:00',
    estimatedMinutes: 20,
    actualMinutes: null,
    priority: PlannerTaskPriority.MEDIUM,
    status: PlannerTaskStatus.PENDING,
    completedAt: null,
    isAutoGenerated: false,
    actionPayload: null,
    createdAt: new Date('2026-10-01T12:00:00Z'),
    updatedAt: new Date('2026-10-01T12:00:00Z'),
    ...overrides,
  });

  const buildPlan = (overrides: Partial<WeeklyPlan> = {}): WeeklyPlan => ({
    id: 'plan-1',
    userId,
    year: Number(today.slice(0, 4)),
    weekNumber: 1,
    startDate: '2026-12-27',
    endDate: '2027-01-02',
    status: WeeklyPlanStatus.ACTIVE,
    notes: null,
    createdAt: new Date('2026-10-01T12:00:00Z'),
    updatedAt: new Date('2026-10-01T12:00:00Z'),
    ...overrides,
  });

  const buildGoal = (overrides: Partial<WeeklyGoal> = {}): WeeklyGoal => ({
    id: 'goal-1',
    planId: 'plan-1',
    category: PlannerGoalCategory.KANJI,
    name: 'Kanji Revisados',
    kanjiGlyph: '字',
    targetValue: 50,
    currentValue: 0,
    unit: '',
    createdAt: new Date('2026-10-01T12:00:00Z'),
    updatedAt: new Date('2026-10-01T12:00:00Z'),
    ...overrides,
  });

  beforeEach(async () => {
    repository = {
      findUserPreferences: jest
        .fn()
        .mockResolvedValue({ timezone: DEFAULT_TIMEZONE }),
      findStreak: jest.fn().mockResolvedValue(null),
      findDailyGoal: jest.fn().mockResolvedValue(null),
      countTasksByDate: jest.fn().mockResolvedValue({ total: 0, completed: 0 }),
      findTaskById: jest.fn(),
      findTasks: jest.fn().mockResolvedValue([]),
      createTask: jest.fn(),
      deleteTask: jest.fn(),
      updateTaskFields: jest.fn(),
      setTaskStatus: jest.fn(),
      findTaskHistory: jest.fn().mockResolvedValue([]),
      registerStreakActivity: jest.fn().mockResolvedValue({ created: true }),
      findPlanByWeek: jest.fn(),
      findPlanById: jest.fn(),
      findGoals: jest.fn().mockResolvedValue([]),
      ensurePlan: jest.fn(),
      updatePlan: jest.fn(),
      upsertGoal: jest.fn(),
      syncGoalCurrents: jest.fn().mockResolvedValue(undefined),
    };

    const module: TestingModule = await Test.createTestingModule({
      providers: [
        PlannerService,
        { provide: PlannerRepository, useValue: repository },
      ],
    }).compile();

    service = module.get(PlannerService);
  });

  // ─── Tarefas ───────────────────────────────────────────────────────────────

  it('cria tarefa com defaults e a semana do plano', async () => {
    const plan = buildPlan();
    repository.ensurePlan.mockResolvedValue(plan);
    repository.createTask.mockResolvedValue(
      buildTask({ weeklyPlanId: plan.id }),
    );

    const result = await service.createTask(userId, {
      title: 'Revisar kanjis',
      date: today,
    });

    expect(repository.ensurePlan).toHaveBeenCalledWith(
      userId,
      expect.objectContaining({
        year: Number(today.slice(0, 4)),
        startDate: expect.stringMatching(/^\d{4}-\d{2}-\d{2}$/) as string,
        endDate: expect.stringMatching(/^\d{4}-\d{2}-\d{2}$/) as string,
      }),
      expect.any(Array),
    );
    expect(repository.createTask).toHaveBeenCalledWith(
      expect.objectContaining({
        userId,
        weeklyPlanId: plan.id,
        category: PlannerCategory.GENERAL,
        kanjiGlyph: '全',
        priority: PlannerTaskPriority.MEDIUM,
        estimatedMinutes: 20,
      }),
    );
    expect(result.categoryLabel).toBe('Geral');
    expect(result.status).toBe(PlannerTaskStatus.PENDING);
  });

  it('cria tarefa KANJI com glyph e label do frontend', async () => {
    repository.ensurePlan.mockResolvedValue(buildPlan());
    repository.createTask.mockResolvedValue(
      buildTask({ category: PlannerCategory.KANJI, kanjiGlyph: '字' }),
    );

    const result = await service.createTask(userId, {
      title: 'Kanji do dia',
      date: today,
      category: PlannerCategory.KANJI,
      estimatedMinutes: 30,
      priority: PlannerTaskPriority.HIGH,
      scheduledTime: '08:00',
    });

    expect(repository.createTask).toHaveBeenCalledWith(
      expect.objectContaining({
        category: PlannerCategory.KANJI,
        kanjiGlyph: '字',
        estimatedMinutes: 30,
        priority: PlannerTaskPriority.HIGH,
        scheduledTime: '08:00',
      }),
    );
    expect(result.categoryLabel).toBe('Kanji');
    expect(result.kanjiGlyph).toBe('字');
  });

  it('lista tarefas repassando os filtros da query', async () => {
    repository.findTasks.mockResolvedValue([
      buildTask(),
      buildTask({ id: 'task-2' }),
    ]);

    const result = await service.listTasks(userId, {
      date: today,
      status: PlannerTaskStatus.PENDING,
    });

    expect(repository.findTasks).toHaveBeenCalledWith(userId, {
      date: today,
      startDate: undefined,
      endDate: undefined,
      status: PlannerTaskStatus.PENDING,
      category: undefined,
    });
    expect(result).toHaveLength(2);
    expect(result[0].id).toBe('task-1');
  });

  it('getTask lança 404 quando a tarefa não existe', async () => {
    repository.findTaskById.mockResolvedValue(null);
    await expect(service.getTask(userId, 'missing')).rejects.toThrow(
      NotFoundException,
    );
  });

  it('deleteTask lança 404 quando não pertence ao usuário', async () => {
    repository.deleteTask.mockResolvedValue(false);
    await expect(service.deleteTask(userId, 'foreign')).rejects.toThrow(
      NotFoundException,
    );
  });

  it('deleteTask retorna success quando removida', async () => {
    repository.deleteTask.mockResolvedValue(true);
    await expect(service.deleteTask(userId, 'task-1')).resolves.toEqual({
      success: true,
      id: 'task-1',
    });
  });

  it('updateTask com mudança de status avalia o dia e devolve status novo', async () => {
    const completed = buildTask({
      status: PlannerTaskStatus.COMPLETED,
      completedAt: new Date(),
      actualMinutes: 20,
    });
    repository.updateTaskFields.mockResolvedValue({
      ok: true,
      task: completed,
      transitioned: true,
    });
    repository.countTasksByDate.mockResolvedValue({ total: 5, completed: 4 });

    const result = await service.updateTask(userId, 'task-1', {
      status: PlannerTaskStatus.COMPLETED,
    });

    expect(repository.updateTaskFields).toHaveBeenCalledWith(
      userId,
      'task-1',
      expect.objectContaining({ status: PlannerTaskStatus.COMPLETED }),
    );
    expect(repository.countTasksByDate).toHaveBeenCalledWith(userId, today);
    expect(repository.registerStreakActivity).toHaveBeenCalled();
    expect(result.status).toBe(PlannerTaskStatus.COMPLETED);
  });

  it('updateTask lança 404 quando o repositório não encontra', async () => {
    repository.updateTaskFields.mockResolvedValue({
      ok: false,
      reason: 'not_found',
    });
    await expect(
      service.updateTask(userId, 'missing', { title: 'Novo' }),
    ).rejects.toThrow(NotFoundException);
  });

  // ─── Conclusão idempotente + threshold 80% ─────────────────────────────────

  it('completeTask conclui tarefa pendente e avalia o dia', async () => {
    repository.findTaskById.mockResolvedValue(buildTask());
    repository.setTaskStatus.mockResolvedValue({
      ok: true,
      task: buildTask({
        status: PlannerTaskStatus.COMPLETED,
        completedAt: new Date(),
        actualMinutes: 20,
      }),
      transitioned: true,
    });
    repository.countTasksByDate.mockResolvedValue({ total: 5, completed: 4 });

    const result = await service.completeTask(userId, 'task-1', {});

    expect(repository.setTaskStatus).toHaveBeenCalledWith(
      userId,
      'task-1',
      PlannerTaskStatus.COMPLETED,
      expect.any(Date),
      undefined,
    );
    // 4/5 = 80% → dia bom registra streak
    expect(repository.registerStreakActivity).toHaveBeenCalledWith({
      userId,
      activityDate: today,
      timezone: DEFAULT_TIMEZONE,
    });
    expect(result.status).toBe(PlannerTaskStatus.COMPLETED);
  });

  it('completeTask é idempotente: já concluída não reprocessa histórico/streak', async () => {
    const done = buildTask({
      status: PlannerTaskStatus.COMPLETED,
      completedAt: new Date(),
    });
    repository.findTaskById.mockResolvedValue(done);
    repository.setTaskStatus.mockResolvedValue({
      ok: true,
      task: done,
      transitioned: false,
    });

    const result = await service.completeTask(userId, 'task-1', {
      completed: true,
    });

    expect(repository.setTaskStatus).toHaveBeenCalledWith(
      userId,
      'task-1',
      PlannerTaskStatus.COMPLETED,
      expect.any(Date),
      undefined,
    );
    expect(repository.countTasksByDate).not.toHaveBeenCalled();
    expect(repository.registerStreakActivity).not.toHaveBeenCalled();
    expect(result.id).toBe('task-1');
  });

  it('completeTask sem body faz toggle (reabre tarefa concluída)', async () => {
    const done = buildTask({ status: PlannerTaskStatus.COMPLETED });
    repository.findTaskById.mockResolvedValue(done);
    repository.setTaskStatus.mockResolvedValue({
      ok: true,
      task: buildTask({ status: PlannerTaskStatus.PENDING }),
      transitioned: true,
    });

    await service.completeTask(userId, 'task-1', {});

    expect(repository.setTaskStatus).toHaveBeenCalledWith(
      userId,
      'task-1',
      PlannerTaskStatus.PENDING,
      expect.any(Date),
      undefined,
    );
    // Reabrir não mexe no streak
    expect(repository.registerStreakActivity).not.toHaveBeenCalled();
  });

  it('não registra streak abaixo do threshold de 80%', async () => {
    repository.findTaskById.mockResolvedValue(buildTask());
    repository.setTaskStatus.mockResolvedValue({
      ok: true,
      task: buildTask({ status: PlannerTaskStatus.COMPLETED }),
      transitioned: true,
    });
    repository.countTasksByDate.mockResolvedValue({ total: 10, completed: 7 }); // 70%

    await service.completeTask(userId, 'task-1', {});

    expect(repository.registerStreakActivity).not.toHaveBeenCalled();
  });

  it('registra streak exatamente no threshold de 80%', async () => {
    repository.findTaskById.mockResolvedValue(buildTask());
    repository.setTaskStatus.mockResolvedValue({
      ok: true,
      task: buildTask({ status: PlannerTaskStatus.COMPLETED }),
      transitioned: true,
    });
    repository.countTasksByDate.mockResolvedValue({ total: 5, completed: 4 });

    await service.completeTask(userId, 'task-1', {});

    expect(repository.registerStreakActivity).toHaveBeenCalled();
  });

  it('daily_goal concluída ativa o streak mesmo abaixo do threshold', async () => {
    repository.findTaskById.mockResolvedValue(buildTask());
    repository.setTaskStatus.mockResolvedValue({
      ok: true,
      task: buildTask({ status: PlannerTaskStatus.COMPLETED }),
      transitioned: true,
    });
    repository.countTasksByDate.mockResolvedValue({ total: 10, completed: 1 });
    repository.findDailyGoal.mockResolvedValue({ isCompleted: true });

    await service.completeTask(userId, 'task-1', {});

    expect(repository.registerStreakActivity).toHaveBeenCalled();
  });

  it('não avalia streak para tarefas de datas que não são hoje', async () => {
    const tomorrowStr = new Date(Date.now() + 86_400_000)
      .toISOString()
      .slice(0, 10);
    repository.findTaskById.mockResolvedValue(buildTask({ date: tomorrowStr }));
    repository.setTaskStatus.mockResolvedValue({
      ok: true,
      task: buildTask({
        date: tomorrowStr,
        status: PlannerTaskStatus.COMPLETED,
      }),
      transitioned: true,
    });

    await service.completeTask(userId, 'task-1', {});

    expect(repository.countTasksByDate).not.toHaveBeenCalled();
    expect(repository.registerStreakActivity).not.toHaveBeenCalled();
  });

  it('completeTask lança 404 para tarefa inexistente', async () => {
    repository.findTaskById.mockResolvedValue(null);
    await expect(
      service.completeTask(userId, 'missing', { completed: true }),
    ).rejects.toThrow(NotFoundException);
  });

  // ─── Histórico ─────────────────────────────────────────────────────────────

  it('getTaskHistory devolve transições status_antigo → status_novo', async () => {
    repository.findTaskById.mockResolvedValue(buildTask());
    repository.findTaskHistory.mockResolvedValue([
      {
        id: 'hist-1',
        taskId: 'task-1',
        oldStatus: PlannerTaskStatus.PENDING,
        newStatus: PlannerTaskStatus.COMPLETED,
        changedAt: new Date('2026-10-10T12:00:00Z'),
      },
    ]);

    const history = await service.getTaskHistory(userId, 'task-1');

    expect(history).toEqual([
      {
        id: 'hist-1',
        taskId: 'task-1',
        oldStatus: PlannerTaskStatus.PENDING,
        newStatus: PlannerTaskStatus.COMPLETED,
        changedAt: '2026-10-10T12:00:00.000Z',
      },
    ]);
  });

  it('getTaskHistory lança 404 para tarefa de outro usuário', async () => {
    repository.findTaskById.mockResolvedValue(null);
    await expect(service.getTaskHistory(userId, 'foreign')).rejects.toThrow(
      NotFoundException,
    );
  });

  // ─── Resumo do dia ─────────────────────────────────────────────────────────

  it('getTodaySummary calcula tarefas, minutos, categorias e streak', async () => {
    repository.findTasks.mockResolvedValue([
      buildTask({
        id: 'task-1',
        status: PlannerTaskStatus.COMPLETED,
        actualMinutes: 25,
        completedAt: new Date(),
      }),
      buildTask({ id: 'task-2', category: PlannerCategory.VOCABULARY }),
    ]);
    repository.findStreak.mockResolvedValue({
      currentStreak: 3,
      longestStreak: 10,
    });

    const summary = await service.getTodaySummary(userId);

    expect(summary).toEqual({
      totalTasks: 2,
      completedTasks: 1,
      pendingTasks: 1,
      completionPercentage: 50,
      minutesStudied: 25,
      categoriesStudied: ['KANJI'],
      streak: 3,
    });
  });

  it('getTodaySummary sem tarefas retorna zeros', async () => {
    repository.findTasks.mockResolvedValue([]);
    const summary = await service.getTodaySummary(userId);
    expect(summary).toEqual({
      totalTasks: 0,
      completedTasks: 0,
      pendingTasks: 0,
      completionPercentage: 0,
      minutesStudied: 0,
      categoriesStudied: [],
      streak: 0,
    });
  });

  // ─── Plano semanal + metas ─────────────────────────────────────────────────

  it('getWeek cria/recebe plano com metas e calcula progresso', async () => {
    const plan = buildPlan();
    repository.ensurePlan.mockResolvedValue(plan);
    repository.findGoals.mockResolvedValue([
      buildGoal({ id: 'goal-1', targetValue: 50 }),
      buildGoal({
        id: 'goal-2',
        category: PlannerGoalCategory.IMMERSION,
        name: 'Tempo de Imersão',
        kanjiGlyph: '時',
        targetValue: 300,
        unit: 'min',
      }),
    ]);
    repository.findTasks.mockResolvedValue([
      buildTask({ status: PlannerTaskStatus.COMPLETED, actualMinutes: 60 }),
      buildTask({
        id: 'task-2',
        category: PlannerCategory.IMMERSION,
        status: PlannerTaskStatus.COMPLETED,
        actualMinutes: 45,
      }),
    ]);

    const week = await service.getWeek(userId, { date: today });

    expect(week.id).toBe(plan.id);
    expect(week.goals).toHaveLength(2);
    const kanjiGoal = week.goals.find(
      (goal) => goal.category === PlannerGoalCategory.KANJI,
    );
    const immersionGoal = week.goals.find(
      (goal) => goal.category === PlannerGoalCategory.IMMERSION,
    );
    // Contagem: 1 tarefa KANJI concluída; tempo: 45 min de imersão
    expect(kanjiGoal?.currentValue).toBe(1);
    expect(kanjiGoal?.percentage).toBe(2);
    expect(immersionGoal?.currentValue).toBe(45);
    expect(repository.syncGoalCurrents).toHaveBeenCalled();
  });

  it('getWeek com year/weekNumber inexistente lança 404', async () => {
    repository.findPlanByWeek.mockResolvedValue(null);
    await expect(
      service.getWeek(userId, { year: 2026, weekNumber: 41 }),
    ).rejects.toThrow(NotFoundException);
  });

  it('updateWeek 404 para plano de outro usuário', async () => {
    repository.findPlanById.mockResolvedValue(null);
    await expect(
      service.updateWeek(userId, 'foreign', { notes: 'x' }),
    ).rejects.toThrow(NotFoundException);
  });

  it('updateWeek aplica status/notes', async () => {
    const plan = buildPlan();
    repository.findPlanById
      .mockResolvedValueOnce(plan)
      .mockResolvedValueOnce({ ...plan, status: WeeklyPlanStatus.COMPLETED });
    repository.updatePlan.mockResolvedValue(true);
    repository.findGoals.mockResolvedValue([]);
    repository.findTasks.mockResolvedValue([]);

    const result = await service.updateWeek(userId, plan.id, {
      status: WeeklyPlanStatus.COMPLETED,
    });

    expect(repository.updatePlan).toHaveBeenCalledWith(userId, plan.id, {
      status: WeeklyPlanStatus.COMPLETED,
    });
    expect(result.status).toBe(WeeklyPlanStatus.COMPLETED);
  });

  it('updateWeekGoals faz upsert com defaults', async () => {
    const plan = buildPlan();
    repository.findPlanById.mockResolvedValue(plan);
    repository.upsertGoal.mockResolvedValue(buildGoal({ targetValue: 60 }));
    repository.findGoals.mockResolvedValue([buildGoal({ targetValue: 60 })]);
    repository.findTasks.mockResolvedValue([]);

    const result = await service.updateWeekGoals(userId, plan.id, {
      goals: [{ category: PlannerGoalCategory.KANJI, targetValue: 60 }],
    });

    expect(repository.upsertGoal).toHaveBeenCalledWith(
      plan.id,
      expect.objectContaining({
        category: PlannerGoalCategory.KANJI,
        name: 'Kanji Revisados',
        kanjiGlyph: '字',
        targetValue: 60,
        unit: '',
      }),
    );
    expect(result.goals[0].targetValue).toBe(60);
  });

  it('updateWeekGoals 404 para plano inexistente', async () => {
    repository.findPlanById.mockResolvedValue(null);
    await expect(
      service.updateWeekGoals(userId, 'missing', {
        goals: [{ category: PlannerGoalCategory.KANJI, targetValue: 10 }],
      }),
    ).rejects.toThrow(NotFoundException);
  });

  // ─── Overview ──────────────────────────────────────────────────────────────

  it('getOverview monta semana, hábitos, tarefas do dia e resumo', async () => {
    repository.ensurePlan.mockResolvedValue(buildPlan());
    repository.findTasks.mockResolvedValue([buildTask()]);
    repository.findStreak.mockResolvedValue({
      currentStreak: 5,
      longestStreak: 10,
    });
    repository.findGoals.mockResolvedValue([
      buildGoal({ targetValue: 50 }),
      buildGoal({
        id: 'goal-3',
        category: PlannerGoalCategory.VOCABULARY,
        name: 'Palavras Novas/Revisão',
        kanjiGlyph: '語',
        targetValue: 100,
      }),
      buildGoal({
        id: 'goal-4',
        category: PlannerGoalCategory.IMMERSION,
        name: 'Tempo de Imersão',
        kanjiGlyph: '時',
        targetValue: 300,
        unit: 'min',
      }),
      buildGoal({
        id: 'goal-5',
        category: PlannerGoalCategory.GENERAL_REVIEW,
        name: 'Revisões Gerais',
        kanjiGlyph: '復',
        targetValue: 200,
      }),
      buildGoal({
        id: 'goal-6',
        category: PlannerGoalCategory.GRAMMAR,
        name: 'Pontos Gramaticais',
        kanjiGlyph: '文',
        targetValue: 10,
      }),
    ]);

    const overview = await service.getOverview(userId, today);

    expect(overview.week).toHaveLength(7);
    expect(overview.week.some((day) => day.isToday)).toBe(true);
    const [todayTask] = overview.todayTasks;
    expect(todayTask).toEqual(
      expect.objectContaining({
        id: 'task-1',
        domain: 'kanji',
        task: 'Revisar kanjis',
        priority: 'medium',
        completed: false,
        dueAt: `${today}T19:00:00`,
      }),
    );
    expect(todayTask?.action).toEqual(
      expect.objectContaining({ type: 'review_kanji' }),
    );
    expect(overview.habits.map((habit) => habit.domain)).toEqual([
      'kanji',
      'vocabulary',
      'grammar',
      'immersion',
      'general',
    ]);
    expect(overview.summary).toEqual(
      expect.objectContaining({
        currentStreakDays: 5,
        longestStreakDays: 10,
        todayDateLabel: expect.stringMatching(/^\S/) as string,
      }),
    );
    expect(overview.weeklyGoals).toHaveLength(5);
  });
});
