import { Test, TestingModule } from '@nestjs/testing';
import {
  PlannerCategory,
  PlannerTaskPriority,
  PlannerTaskStatus,
} from '@prisma/client';
import { PlannerRepository } from './planner.repository';
import { PrismaService } from '../../auth/repositories/prisma.service';

type TxMock = {
  plannerTask: {
    findFirst: jest.Mock;
    updateMany: jest.Mock;
    update: jest.Mock;
    findUniqueOrThrow: jest.Mock;
  };
  plannerHistory: { create: jest.Mock };
  streak: { upsert: jest.Mock; update: jest.Mock };
  streakHistory: { findUnique: jest.Mock; create: jest.Mock };
};

describe('PlannerRepository', () => {
  let repository: PlannerRepository;
  let prisma: { $transaction: jest.Mock };
  let tx: TxMock;

  const userId = 'user-1';
  const taskId = 'task-1';

  const buildTask = (overrides: Record<string, unknown> = {}) => ({
    id: taskId,
    userId,
    weeklyPlanId: 'plan-1',
    title: 'Tarefa',
    description: null,
    category: PlannerCategory.KANJI,
    kanjiGlyph: '字',
    date: '2026-10-10',
    scheduledTime: null,
    estimatedMinutes: 20,
    actualMinutes: null,
    priority: PlannerTaskPriority.MEDIUM,
    status: PlannerTaskStatus.PENDING,
    completedAt: null,
    isAutoGenerated: false,
    actionPayload: null,
    createdAt: new Date('2026-10-01T12:00:00Z'),
    updatedAt: new Date('2026-10-01T12:00:00Z'),
    ...overrides,
  });

  /** Primeiro argumento da primeira chamada do mock (tipado, segue padrão do repo). */
  const firstCall = <T>(mock: jest.Mock): T => {
    const calls = mock.mock.calls as unknown[][];
    return calls[0][0] as T;
  };

  beforeEach(async () => {
    tx = {
      plannerTask: {
        findFirst: jest.fn(),
        updateMany: jest.fn(),
        update: jest.fn(),
        findUniqueOrThrow: jest.fn(),
      },
      plannerHistory: { create: jest.fn() },
      streak: { upsert: jest.fn(), update: jest.fn() },
      streakHistory: { findUnique: jest.fn(), create: jest.fn() },
    };

    prisma = {
      $transaction: jest.fn(async (arg: unknown) => {
        if (typeof arg === 'function') {
          return (arg as (client: TxMock) => unknown)(tx);
        }
        return Promise.all(arg as Promise<unknown>[]);
      }),
    };

    const module: TestingModule = await Test.createTestingModule({
      providers: [
        PlannerRepository,
        { provide: PrismaService, useValue: prisma },
      ],
    }).compile();

    repository = module.get(PlannerRepository);
  });

  // ─── setTaskStatus (PATCH /complete) ───────────────────────────────────────

  it('não cria histórico quando a tarefa já está no estado alvo', async () => {
    const done = buildTask({ status: PlannerTaskStatus.COMPLETED });
    tx.plannerTask.findFirst.mockResolvedValue(done);

    const result = await repository.setTaskStatus(
      userId,
      taskId,
      PlannerTaskStatus.COMPLETED,
    );

    expect(result).toEqual({ ok: true, task: done, transitioned: false });
    expect(tx.plannerTask.updateMany).not.toHaveBeenCalled();
    expect(tx.plannerHistory.create).not.toHaveBeenCalled();
  });

  it('transição PENDING → COMPLETED grava 1 histórico antigo → novo', async () => {
    const pending = buildTask();
    const completed = buildTask({
      status: PlannerTaskStatus.COMPLETED,
      completedAt: new Date(),
    });
    tx.plannerTask.findFirst.mockResolvedValue(pending);
    tx.plannerTask.updateMany.mockResolvedValue({ count: 1 });
    tx.plannerTask.findUniqueOrThrow.mockResolvedValue(completed);

    const result = await repository.setTaskStatus(
      userId,
      taskId,
      PlannerTaskStatus.COMPLETED,
      new Date('2026-10-10T12:00:00Z'),
      30,
    );

    const updateManyCall = firstCall<{
      where: { id: string; userId: string; status: PlannerTaskStatus };
      data: Record<string, unknown>;
    }>(tx.plannerTask.updateMany);
    expect(updateManyCall.where).toEqual({
      id: taskId,
      userId,
      status: PlannerTaskStatus.PENDING,
    });
    expect(updateManyCall.data).toEqual(
      expect.objectContaining({
        status: PlannerTaskStatus.COMPLETED,
        actualMinutes: 30,
      }),
    );
    expect(tx.plannerHistory.create).toHaveBeenCalledTimes(1);
    expect(tx.plannerHistory.create).toHaveBeenCalledWith({
      data: {
        taskId,
        oldStatus: PlannerTaskStatus.PENDING,
        newStatus: PlannerTaskStatus.COMPLETED,
      },
    });
    expect(result.ok).toBe(true);
  });

  it('guard atômico falhou (corrida) → no_change sem histórico', async () => {
    tx.plannerTask.findFirst.mockResolvedValue(buildTask());
    tx.plannerTask.updateMany.mockResolvedValue({ count: 0 });

    const result = await repository.setTaskStatus(
      userId,
      taskId,
      PlannerTaskStatus.COMPLETED,
    );

    expect(result).toEqual({ ok: false, reason: 'no_change' });
    expect(tx.plannerHistory.create).not.toHaveBeenCalled();
  });

  it('tarefa inexistente → not_found', async () => {
    tx.plannerTask.findFirst.mockResolvedValue(null);
    const result = await repository.setTaskStatus(
      userId,
      taskId,
      PlannerTaskStatus.COMPLETED,
    );
    expect(result).toEqual({ ok: false, reason: 'not_found' });
  });

  // ─── updateTaskFields (PATCH /tasks/:id) ───────────────────────────────────

  it('atualização sem mudança de status não cria histórico', async () => {
    const task = buildTask();
    tx.plannerTask.findFirst.mockResolvedValue(task);
    tx.plannerTask.update.mockResolvedValue({ ...task, title: 'Novo título' });

    const result = await repository.updateTaskFields(userId, taskId, {
      title: 'Novo título',
    });

    expect(tx.plannerHistory.create).not.toHaveBeenCalled();
    expect(result.ok).toBe(true);
    expect(result.ok && result.transitioned).toBe(false);
  });

  it('atualização com status cria histórico e ajusta completedAt', async () => {
    const task = buildTask();
    tx.plannerTask.findFirst.mockResolvedValue(task);
    tx.plannerTask.update.mockResolvedValue(
      buildTask({ status: PlannerTaskStatus.COMPLETED }),
    );

    await repository.updateTaskFields(
      userId,
      taskId,
      { status: PlannerTaskStatus.COMPLETED },
      new Date('2026-10-10T12:00:00Z'),
    );

    expect(tx.plannerHistory.create).toHaveBeenCalledWith({
      data: {
        taskId,
        oldStatus: PlannerTaskStatus.PENDING,
        newStatus: PlannerTaskStatus.COMPLETED,
      },
    });
    const updateCall = firstCall<{ data: Record<string, unknown> }>(
      tx.plannerTask.update,
    );
    expect(updateCall.data).toEqual(
      expect.objectContaining({
        status: PlannerTaskStatus.COMPLETED,
        completedAt: new Date('2026-10-10T12:00:00Z'),
      }),
    );
  });

  it('updateTaskFields retorna not_found para tarefa alheia', async () => {
    tx.plannerTask.findFirst.mockResolvedValue(null);
    const result = await repository.updateTaskFields(userId, 'foreign', {
      title: 'x',
    });
    expect(result).toEqual({ ok: false, reason: 'not_found' });
  });

  // ─── registerStreakActivity (dia bom ≥ 80%) ────────────────────────────────

  const buildStreak = (overrides: Record<string, unknown> = {}) => ({
    id: 'streak-1',
    userId,
    currentStreak: 3,
    longestStreak: 7,
    lastActivityDate: '2026-10-09',
    freezesAvailable: 3,
    freezesUsed: 0,
    totalActiveDays: 5,
    createdAt: new Date('2026-10-01T12:00:00Z'),
    updatedAt: new Date('2026-10-01T12:00:00Z'),
    ...overrides,
  });

  it('não duplica nó de streak nem incrementa duas vezes no mesmo dia', async () => {
    tx.streak.upsert.mockResolvedValue(buildStreak());
    tx.streakHistory.findUnique.mockResolvedValue({ id: 'hist-existing' });

    const result = await repository.registerStreakActivity({
      userId,
      activityDate: '2026-10-10',
      timezone: 'America/Sao_Paulo',
    });

    expect(result).toEqual({ created: false });
    expect(tx.streakHistory.create).not.toHaveBeenCalled();
    expect(tx.streak.update).not.toHaveBeenCalled();
  });

  it('dia sequencial (ontem) incrementa currentStreak e totalActiveDays', async () => {
    tx.streak.upsert.mockResolvedValue(buildStreak());
    tx.streakHistory.findUnique.mockResolvedValue(null);

    const result = await repository.registerStreakActivity({
      userId,
      activityDate: '2026-10-10',
      timezone: 'America/Sao_Paulo',
    });

    expect(result).toEqual({ created: true });
    expect(tx.streakHistory.create).toHaveBeenCalledWith({
      data: {
        userId,
        streakId: 'streak-1',
        activityDate: '2026-10-10',
        timezone: 'America/Sao_Paulo',
      },
    });
    expect(tx.streak.update).toHaveBeenCalledWith({
      where: { id: 'streak-1' },
      data: {
        currentStreak: 4,
        longestStreak: 7,
        lastActivityDate: '2026-10-10',
        totalActiveDays: 6,
      },
    });
  });

  it('lacuna de dias reinicia o streak em 1', async () => {
    tx.streak.upsert.mockResolvedValue(
      buildStreak({ lastActivityDate: '2026-10-01' }),
    );
    tx.streakHistory.findUnique.mockResolvedValue(null);

    await repository.registerStreakActivity({
      userId,
      activityDate: '2026-10-10',
      timezone: 'America/Sao_Paulo',
    });

    const streakUpdate = firstCall<{
      where: { id: string };
      data: Record<string, unknown>;
    }>(tx.streak.update);
    expect(streakUpdate.data).toEqual(
      expect.objectContaining({ currentStreak: 1 }),
    );
  });

  it('primeiro dia (sem lastActivityDate) inicia streak em 1', async () => {
    tx.streak.upsert.mockResolvedValue(
      buildStreak({
        lastActivityDate: null,
        currentStreak: 0,
        longestStreak: 0,
        totalActiveDays: 0,
      }),
    );
    tx.streakHistory.findUnique.mockResolvedValue(null);

    await repository.registerStreakActivity({
      userId,
      activityDate: '2026-10-10',
      timezone: 'America/Sao_Paulo',
    });

    const firstDay = firstCall<{
      where: { id: string };
      data: Record<string, unknown>;
    }>(tx.streak.update);
    expect(firstDay.data).toEqual(
      expect.objectContaining({
        currentStreak: 1,
        longestStreak: 1,
        totalActiveDays: 1,
      }),
    );
  });
});
