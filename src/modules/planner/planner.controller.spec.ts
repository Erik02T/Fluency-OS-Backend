import {
  ExecutionContext,
  INestApplication,
  NotFoundException,
  UnauthorizedException,
  ValidationPipe,
} from '@nestjs/common';
import { Test } from '@nestjs/testing';
import { Server } from 'http';
import request from 'supertest';
import { PlannerController } from './planner.controller';
import { PlannerService } from './planner.service';
import { JwtAuthGuard } from '../auth/guards/jwt-auth.guard';

describe('PlannerController', () => {
  let app: INestApplication;
  const plannerService = {
    createTask: jest.fn(),
    listTasks: jest.fn(),
    getTask: jest.fn(),
    updateTask: jest.fn(),
    deleteTask: jest.fn(),
    completeTask: jest.fn(),
    getTaskHistory: jest.fn(),
    getTodaySummary: jest.fn(),
    getOverview: jest.fn(),
    getWeek: jest.fn(),
    updateWeek: jest.fn(),
    updateWeekGoals: jest.fn(),
  };

  let jwtGuardError: Error | null = null;

  beforeEach(async () => {
    const moduleRef = await Test.createTestingModule({
      controllers: [PlannerController],
      providers: [
        { provide: PlannerService, useValue: plannerService },
        JwtAuthGuard,
      ],
    })
      .overrideGuard(JwtAuthGuard)
      .useValue({
        canActivate: jest.fn((context: ExecutionContext) => {
          if (jwtGuardError) {
            throw jwtGuardError;
          }
          const req = context
            .switchToHttp()
            .getRequest<{ user?: { id: string } }>();
          req.user = { id: 'user-123' };
          return true;
        }),
      })
      .compile();

    app = moduleRef.createNestApplication();
    app.useGlobalPipes(
      new ValidationPipe({ whitelist: true, transform: true }),
    );
    await app.init();

    jwtGuardError = null;
    jest.clearAllMocks();
  });

  afterEach(async () => {
    await app.close();
  });

  const httpServer = (): Server => app.getHttpServer() as Server;

  const taskResponse = {
    id: 'task-1',
    userId: 'user-123',
    weeklyPlanId: 'plan-1',
    title: 'Revisar kanjis',
    description: null,
    category: 'KANJI',
    categoryLabel: 'Kanji',
    kanjiGlyph: '字',
    date: '2026-10-10',
    scheduledTime: '19:00',
    estimatedMinutes: 20,
    actualMinutes: null,
    priority: 'MEDIUM',
    status: 'PENDING',
    completedAt: null,
    isAutoGenerated: false,
    actionPayload: null,
    createdAt: '2026-10-01T12:00:00.000Z',
    updatedAt: '2026-10-01T12:00:00.000Z',
  };

  const planResponse = {
    id: 'plan-1',
    userId: 'user-123',
    year: 2026,
    weekNumber: 41,
    startDate: '2026-10-04',
    endDate: '2026-10-10',
    status: 'ACTIVE',
    notes: null,
    goals: [],
    createdAt: '2026-10-01T12:00:00.000Z',
    updatedAt: '2026-10-01T12:00:00.000Z',
  };

  it('POST /planner/tasks cria tarefa com 201', async () => {
    plannerService.createTask.mockResolvedValue(taskResponse);

    await request(httpServer())
      .post('/planner/tasks')
      .send({ title: 'Revisar kanjis', date: '2026-10-10', category: 'KANJI' })
      .expect(201)
      .expect((res: { body: { id: string } }) => {
        expect(res.body.id).toBe('task-1');
      });

    expect(plannerService.createTask).toHaveBeenCalledWith('user-123', {
      title: 'Revisar kanjis',
      date: '2026-10-10',
      category: 'KANJI',
    });
  });

  it('POST /planner/tasks rejeita payload inválido com 400', async () => {
    await request(httpServer())
      .post('/planner/tasks')
      .send({ date: '2026-10-10' })
      .expect(400);

    expect(plannerService.createTask).not.toHaveBeenCalled();
  });

  it('GET /planner/tasks repassa filtros da query', async () => {
    plannerService.listTasks.mockResolvedValue([taskResponse]);

    await request(httpServer())
      .get('/planner/tasks')
      .query({ date: '2026-10-10', status: 'PENDING' })
      .expect(200)
      .expect((res: { body: unknown[] }) => {
        expect(res.body).toHaveLength(1);
      });

    expect(plannerService.listTasks).toHaveBeenCalledWith('user-123', {
      date: '2026-10-10',
      status: 'PENDING',
    });
  });

  it('PATCH /planner/tasks/:id/complete altera o status', async () => {
    plannerService.completeTask.mockResolvedValue({
      ...taskResponse,
      status: 'COMPLETED',
      completedAt: '2026-10-10T12:00:00.000Z',
    });

    await request(httpServer())
      .patch('/planner/tasks/task-1/complete')
      .send({ completed: true, actualMinutes: 25 })
      .expect(200)
      .expect((res: { body: { status: string } }) => {
        expect(res.body.status).toBe('COMPLETED');
      });

    expect(plannerService.completeTask).toHaveBeenCalledWith(
      'user-123',
      'task-1',
      {
        completed: true,
        actualMinutes: 25,
      },
    );
  });

  it('PATCH /planner/tasks/:id atualiza campos', async () => {
    plannerService.updateTask.mockResolvedValue({
      ...taskResponse,
      title: 'Atualizada',
    });

    await request(httpServer())
      .patch('/planner/tasks/task-1')
      .send({ title: 'Atualizada', status: 'COMPLETED' })
      .expect(200);

    expect(plannerService.updateTask).toHaveBeenCalledWith(
      'user-123',
      'task-1',
      {
        title: 'Atualizada',
        status: 'COMPLETED',
      },
    );
  });

  it('DELETE /planner/tasks/:id remove a tarefa', async () => {
    plannerService.deleteTask.mockResolvedValue({
      success: true,
      id: 'task-1',
    });

    await request(httpServer())
      .delete('/planner/tasks/task-1')
      .expect(200)
      .expect((res: { body: { success: boolean } }) => {
        expect(res.body.success).toBe(true);
      });
  });

  it('GET /planner/tasks/:id/history retorna o histórico de status', async () => {
    plannerService.getTaskHistory.mockResolvedValue([
      {
        id: 'hist-1',
        taskId: 'task-1',
        oldStatus: 'PENDING',
        newStatus: 'COMPLETED',
        changedAt: '2026-10-10T12:00:00.000Z',
      },
    ]);

    await request(httpServer())
      .get('/planner/tasks/task-1/history')
      .expect(200)
      .expect((res: { body: unknown[] }) => {
        expect(res.body).toHaveLength(1);
      });
  });

  it('GET /planner/summary/today retorna o resumo do dia', async () => {
    plannerService.getTodaySummary.mockResolvedValue({
      totalTasks: 10,
      completedTasks: 8,
      pendingTasks: 2,
      completionPercentage: 80,
      minutesStudied: 120,
      categoriesStudied: ['KANJI'],
      streak: 3,
    });

    await request(httpServer())
      .get('/planner/summary/today')
      .expect(200)
      .expect((res: { body: { completionPercentage: number } }) => {
        expect(res.body.completionPercentage).toBe(80);
      });
  });

  it('GET /planner/overview repassa a data', async () => {
    plannerService.getOverview.mockResolvedValue({
      week: [],
      habits: [],
      todayTasks: [],
      weeklyGoals: [],
      summary: {},
    });

    await request(httpServer())
      .get('/planner/overview')
      .query({ date: '2026-10-10' })
      .expect(200);

    expect(plannerService.getOverview).toHaveBeenCalledWith(
      'user-123',
      '2026-10-10',
    );
  });

  it('GET /planner/week retorna o plano semanal', async () => {
    plannerService.getWeek.mockResolvedValue(planResponse);

    await request(httpServer())
      .get('/planner/week')
      .query({ date: '2026-10-10' })
      .expect(200)
      .expect((res: { body: { id: string } }) => {
        expect(res.body.id).toBe('plan-1');
      });
  });

  it('PUT /planner/weeks/:id/goals atualiza as metas', async () => {
    plannerService.updateWeekGoals.mockResolvedValue(planResponse);

    await request(httpServer())
      .put('/planner/weeks/plan-1/goals')
      .send({ goals: [{ category: 'IMMERSION', targetValue: 450 }] })
      .expect(200);

    expect(plannerService.updateWeekGoals).toHaveBeenCalledWith(
      'user-123',
      'plan-1',
      { goals: [{ category: 'IMMERSION', targetValue: 450 }] },
    );
  });

  it('PATCH /planner/weeks/:id atualiza status/notes', async () => {
    plannerService.updateWeek.mockResolvedValue({
      ...planResponse,
      status: 'COMPLETED',
    });

    await request(httpServer())
      .patch('/planner/weeks/plan-1')
      .send({ status: 'COMPLETED', notes: 'Semana concluída' })
      .expect(200)
      .expect((res: { body: { status: string } }) => {
        expect(res.body.status).toBe('COMPLETED');
      });
  });

  it('retorna 404 quando o service lança NotFound', async () => {
    plannerService.completeTask.mockRejectedValue(
      new NotFoundException('Planner task missing not found'),
    );

    await request(httpServer())
      .patch('/planner/tasks/missing/complete')
      .send({})
      .expect(404);
  });

  it('retorna 401 sem token JWT', async () => {
    jwtGuardError = new UnauthorizedException();
    await request(httpServer()).get('/planner/summary/today').expect(401);
  });
});
